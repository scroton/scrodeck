// core/test/vt/oracle/gen-tables.js — regenerate core/vt/unicode_v6.inc and core/vt/charsets.inc from the
// xterm.js sources, so the C++ tables are the oracle's tables and not a retyped copy.
//   node core/test/vt/oracle/gen-tables.js <path to @xterm/xterm/src/common>
// (the browser package ships its TypeScript sources; @xterm/headless does not)
'use strict';
const fs = require('fs');
const path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: node gen-tables.js <@xterm/xterm/src/common>'); process.exit(2); }
const out = path.resolve(__dirname, '..', '..', '..', 'vt');

// ---- UnicodeV6 ----
const u = fs.readFileSync(path.join(src, 'input', 'UnicodeV6.ts'), 'utf8');
function ranges(name) {
  const m = new RegExp('const ' + name + ' = \\[([\\s\\S]*?)\\];').exec(u);
  const r = [];
  const re = /\[(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\]/g;
  let x;
  while ((x = re.exec(m[1]))) r.push([x[1], x[2]]);
  return r;
}
const fmt = r => r.map(p => '{' + p[0] + ', ' + p[1] + '}').reduce((acc, s, i) => acc + (i % 4 === 0 ? '\n  ' : ' ') + s + ',', '');
let s = '// GENERATED by core/test/vt/oracle/gen-tables.js from @xterm/xterm src/common/input/UnicodeV6.ts — do not edit.\n';
s += 'static const uint32_t BMP_COMBINING[][2] = {' + fmt(ranges('BMP_COMBINING')) + '\n};\n';
s += 'static const uint32_t HIGH_COMBINING[][2] = {' + fmt(ranges('HIGH_COMBINING')) + '\n};\n';
fs.writeFileSync(path.join(out, 'unicode_v6.inc'), s);

// ---- Charsets ----
const c = fs.readFileSync(path.join(src, 'data', 'Charsets.ts'), 'utf8')
  .replace(/^import .*$/mg, '').replace(/export const/g, 'const').replace(/: \{ \[key: string\]: ICharset \| undefined \}/, '')
  .replace(/: ICharset \| undefined/, '');
const CHARSETS = new Function(c + '\nreturn CHARSETS;')();
let t = '// GENERATED by core/test/vt/oracle/gen-tables.js from @xterm/xterm src/common/data/Charsets.ts — do not edit.\n';
t += '// Charset ids: 0 = US ASCII (no mapping). Each table maps an ASCII code to its replacement (0 = unchanged).\n';
const flags = Object.keys(CHARSETS);
const uniq = [];           // distinct charset objects
const idOf = {};
for (const f of flags) {
  const cs = CHARSETS[f];
  if (!cs) { idOf[f] = 0; continue; }
  let i = uniq.indexOf(cs);
  if (i < 0) { uniq.push(cs); i = uniq.length - 1; }
  idOf[f] = i + 1;
}
t += 'static const int CHARSET_COUNT = ' + (uniq.length + 1) + ';\n';
t += 'static const char16_t CHARSET_MAP[' + (uniq.length + 1) + '][128] = {\n  {0},\n';
for (const cs of uniq) {
  const row = new Array(128).fill(0);
  for (const k of Object.keys(cs)) row[k.charCodeAt(0)] = cs[k].charCodeAt(0);
  t += '  {' + row.map(v => v ? '0x' + v.toString(16) : '0').join(',') + '},\n';
}
t += '};\n';
t += '// final byte of ESC ( <final> etc. -> charset id, -1 = not a registered designator (sequence ignored)\n';
t += 'static int charsetIdForFinal(int f) {\n  switch (f) {\n';
for (const f of flags) t += '    case ' + JSON.stringify(f).replace(/"/g, "'") + ': return ' + idOf[f] + ';\n';
t += '    default: return -1;\n  }\n}\n';
fs.writeFileSync(path.join(out, 'charsets.inc'), t);
console.log('wrote unicode_v6.inc, charsets.inc: ' + flags.length + ' designators, ' + uniq.length + ' tables');
